import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const html=await fs.readFile(new URL('../index.html',import.meta.url),'utf8');
const config=JSON.parse(await fs.readFile(new URL('../vercel.json',import.meta.url),'utf8'));
const origin='https://nextone-opal.vercel.app';
assert.ok(html.includes(`<link rel="canonical" href="${origin}/"`));
assert.match(html,/<html lang="es"/);assert.match(html,/<meta name="description" content="[^"]{60,}"/);
assert.match(html,/<meta name="robots" content="index, follow/);
assert.match(html,/<div id="root"><main[^>]*><h1>nextONE/);
for(const field of ['og:title','og:description','og:image','og:url','twitter:card'])assert.ok(html.includes(`"${field}"`));
const data=html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)[1];
assert.equal(JSON.parse(data)['@type'],'WebSite');assert.equal(JSON.parse(data).url,origin+'/');
const hash=createHash('sha256').update(data).digest('base64');
const csp=config.headers[0].headers.find(h=>h.key==='Content-Security-Policy').value;
assert.ok(csp.includes(`'sha256-${hash}'`));assert.ok(!csp.match(/script-src[^;]*'unsafe-inline'/));
assert.ok(config.headers.some(rule=>rule.has?.some(h=>h.key==='invite')&&rule.headers.some(h=>h.value==='noindex, nofollow')));
const sitemap=await fs.readFile(new URL('../public/sitemap.xml',import.meta.url),'utf8');
assert.equal((sitemap.match(/<loc>/g)||[]).length,1);assert.ok(sitemap.includes(`<loc>${origin}/</loc>`));
const robots=await fs.readFile(new URL('../public/robots.txt',import.meta.url),'utf8');assert.ok(robots.includes(`Sitemap: ${origin}/sitemap.xml`));
console.log('PASS SEO: public HTML, metadata, canonical, social cards, JSON-LD/CSP hash, private query headers, robots and public-only sitemap.');
